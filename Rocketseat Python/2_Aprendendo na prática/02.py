
"""
Exercício 02 - Variáveis do tipo numeros

"""
# Declarando variáveis do tipo inteiro
nascimento = 1995
ano_atual = 2026
idade = ano_atual - nascimento
print(f"Idade: {idade}")

#Adição
adicao = 120 + 80
print(f"Adição: {adicao}")

# Subtração
subtracao = 120 - 80
print(f"Subtração: {subtracao}")

# Multiplicação
multiplicacao = 120 * 80
print(f"Multiplicação: {multiplicacao}")

# Divisão
divisao = 120 / 80
print(f"Divisão: {divisao}")

# Divisão inteira
divisao_inteira = 120 // 80
print(f"Divisão inteira: {divisao_inteira}")

# Resto da divisão
resto_divisao = 120 % 80
print(f"Resto da divisão: {resto_divisao}")

# Exponenciação
exponenciacao = 120 ** 2
print(f"Exponenciação: {exponenciacao}")

#Conversão
numero_str = "120"
numero_int = int(numero_str)
print(f"Número como inteiro: {numero_int}")

numero_float = float(numero_str)
print(f"Número como float: {numero_float}")

